// prepare: result equals expected.json once the bytes are checked against expected/ or the input
const stripBytes = value => {
  if (Array.isArray(value)) return value.forEach(stripBytes);
  if (value && typeof value === "object") {
    delete value.normalized_bytes;
    Object.values(value).forEach(stripBytes);
  }
};
const checkBytes = (item, input, expectedFiles, label) => {
  assert.ok(item.normalized_bytes instanceof Uint8Array, `${label} bytes are a Uint8Array`);
  const want = item.change.kind === "none" ? input.get(item.source_path) : expectedFiles.get(item.output_path);
  assert.deepStrictEqual(Buffer.from(item.normalized_bytes), Buffer.from(want ?? []), `${label} ${item.output_path} bytes`);
};
for (const name of cases("prepare")) {
  const request = json("prepare", name, "request.json");
  const input = tree(join(fixtures, "prepare", name, "input"));
  const result = wasm.prepare({ files: input, context: request.context, declaredDialect: request.declared_dialect ?? undefined, migrate: request.migrate ?? false });
  const expectedDir = join(fixtures, "prepare", name, "expected");
  const expectedFiles = existsSync(expectedDir) ? tree(expectedDir) : new Map();
  for (const item of [result.manifest, ...result.definitions].filter(Boolean)) checkBytes(item, input, expectedFiles, `prepare/${name}`);
  stripBytes(result);
  check(result, json("prepare", name, "expected.json"), `prepare/${name}`);
}
assert.throws(() => wasm.prepare({ files: new Map(), context: "nonsense" }), (e) => e.code === "input.invalid");

// normalize: inspection, the staged inspection and normalization of each fetched remote plugin
// (its own tree, with `hint.plugin` set to the marketplace entry), and the packages equal the
// fixtures; each package's definition and manifest files equal expected/<id>/<path>
const defined = object => Object.fromEntries(Object.entries(object).filter(([, value]) => value !== undefined));
for (const name of cases("normalize")) {
  const dir = join(fixtures, "normalize", name);
  const request = existsSync(join(dir, "request.json")) ? json("normalize", name, "request.json") : {};
  const root = tree(join(dir, "input"));
  const hint = request.hint ?? {};
  const inspection = wasm.inspect({ tree: root, hint });
  check(inspection, json("normalize", name, "inspection.json"), `normalize/${name} inspection`);
  const result = wasm.normalize(defined({ tree: root, source: request.source, hint: request.hint, selection: request.selection }));
  const packages = [...result.packages];
  const remoteInspections = {};
  const remoteNormalized = {};
  for (const [plugin, remote] of Object.entries(request.remote ?? {}).sort(([a], [b]) => (a < b ? -1 : 1))) {
    const fetched = tree(join(dir, remote.dir));
    const entry = inspection.plugins.find(candidate => candidate.entry.name === plugin).entry;
    const remoteHint = { plugin: { entry, at_marketplace_root: false } };
    remoteInspections[plugin] = wasm.inspect({ tree: fetched, hint: remoteHint });
    remoteNormalized[plugin] = wasm.normalize(defined({ tree: fetched, source: remote.source, hint: remoteHint }));
    packages.push(...remoteNormalized[plugin].packages);
  }
  if (existsSync(join(dir, "remote-inspections.json"))) check(remoteInspections, json("normalize", name, "remote-inspections.json"), `normalize/${name} remote inspections`);
  const expectedDir = join(dir, "expected");
  const expectedFiles = existsSync(expectedDir) ? tree(expectedDir) : new Map();
  let produced = 0;
  for (const pkg of packages) {
    for (const file of [pkg.prepared.manifest, ...pkg.prepared.definitions, ...(pkg.prepared.mcp_servers ?? [])].filter(Boolean)) {
      const want = expectedFiles.get(`${pkg.id}/${file.output_path}`);
      assert.ok(file.normalized_bytes instanceof Uint8Array, `normalize/${name} bytes are a Uint8Array`);
      assert.deepStrictEqual(Buffer.from(file.normalized_bytes), Buffer.from(want ?? []), `normalize/${name} ${pkg.id}/${file.output_path} bytes`);
      produced++;
    }
  }
  assert.equal(produced, expectedFiles.size, `normalize/${name} file count`);
  stripBytes(result);
  check(result, json("normalize", name, "normalized.json"), `normalize/${name}`);
  if (existsSync(join(dir, "remote-normalized.json"))) {
    for (const normalized of Object.values(remoteNormalized)) stripBytes(normalized);
    check(remoteNormalized, json("normalize", name, "remote-normalized.json"), `normalize/${name} remote normalized`);
  }
}
assert.throws(() => wasm.normalize({ tree: new Map(), hint: { dialect: "nonsense" } }));

// upgrade: the legacy file in a legacy package comes back as expected.*, with the expected diagnostics
const legacyManifest = '[package]\nname = "legacy"\nversion = "1.0.0"\n';
const enc = new TextEncoder();
for (const name of cases("upgrade")) {
  const kind = text("upgrade", name, "kind.txt").trim();
  if (kind === "payload") continue;
  const ext = kind === "manifest" ? "toml" : "md";
  const path = { manifest: "mars.toml", agent: "agents/probe.md", skill: "skills/probe/SKILL.md" }[kind];
  const files = new Map([["mars.toml", enc.encode(kind === "manifest" ? text("upgrade", name, `input.${ext}`) : legacyManifest)]]);
  if (kind !== "manifest") files.set(path, enc.encode(text("upgrade", name, `input.${ext}`)));
  const result = wasm.prepare({ files, context: "package" });
  const item = kind === "manifest" ? result.manifest : result.definitions.find(d => d.source_path === path);
  assert.equal(Buffer.from(item.normalized_bytes).toString("utf8"), text("upgrade", name, `expected.${ext}`), `upgrade/${name} text`);
  assert.equal(item.change.kind === "fully-rewritten", existsSync(join(fixtures, "upgrade", name, "fully-rewritten.txt")), `upgrade/${name} rewrite mode`);
  const messages = (result.changes?.[path] ?? []).map(d => d.message);
  const keys = json("upgrade", name, "expected-diagnostics.json");
  assert.equal(messages.length, keys.length, `upgrade/${name} diagnostics ${JSON.stringify(messages)}`);
  for (const key of keys) assert.ok(messages.some(m => m.includes(`\`${key}\``)), `upgrade/${name} names ${key}`);
  checked++;
}

// version: the ops the package exports (`parse-constraint` and `parse-tag` are Rust-only). A
// refusal is a thrown Error whose `code` the fixture names.
const attempt = (run) => {
  try { return run(); } catch (error) {
    assert.ok(error instanceof Error && typeof error.code === "string", `a coded Error, got ${error}`);
    return { error: { code: error.code, message: error.message } };
  }
};
for (const name of cases("version")) {
  const input = json("version", name, "input.json");
  const actual = {
    "satisfies": () => attempt(() => ({ satisfied: wasm.satisfies(input.constraint ?? null, input.version) })),
    "satisfies-requirement": () => attempt(() => ({ satisfied: wasm.satisfiesRequirement(input.requirement, input.version) })),
    "select-version": () => attempt(() => wasm.selectVersion({
      available: input.tags, constraints: input.constraints,
      locked: input.locked,
    })),
  }[input.op];
  // `policy` and `excluded` are the binary's (upgrade, engine exclusions); `selectVersion` has neither.
  if (actual && !("policy" in input || "excluded" in input)) check(actual(), json("version", name, "expected.json"), `version/${name}`);
}
assert.equal(attempt(() => wasm.satisfies(null, "1.x")).error.code, "version.invalid-version");
assert.equal(attempt(() => wasm.selectVersion({ available: [], constraints: [], locked: "nightly" })).error.code, "version.invalid-tag");
assert.equal(attempt(() => wasm.selectVersion({ available: [], constraints: [], typo: 1 })).error.code, "input.invalid");

// selection: each package is prepared, then the results go to selectItems as prepare returned them
const selectionCase = (name) => {
  const request = json("selection", name, "request.json");
  const from = request.packages_from ?? name;
  const dir = join(fixtures, "selection", from);
  const packages = {};
  for (const pkg of cases(join("selection", from, "packages"))) {
    packages[pkg] = { prepared: wasm.prepare({ files: tree(join(dir, "packages", pkg)), context: "package" }), extra_items: request.extra_items?.[pkg] };
  }
  const root = request.root ? packages[request.root] : undefined;
  if (request.root) delete packages[request.root];
  return { requests: request.requests, packages, root };
};
for (const name of cases("selection")) {
  check(wasm.selectItems(selectionCase(name)), json("selection", name, "expected.json"), `selection/${name}`);
}
{
  const input = selectionCase("cws-v0.6.1-as-root");
  const refuses = (change) => attempt(() => wasm.selectItems(change(structuredClone(input)))).error?.code;
  assert.equal(refuses(i => ({ ...i, requests: [{ name: "writing-sync", rename: { a: "b" } }] })), "input.invalid", "rename");
  assert.equal(refuses(i => ({ ...i, requests: [{ name: "writing-sync", agnets: ["a"] }] })), "input.invalid", "a typo in a filter");
  assert.equal(refuses(i => ({ ...i, root: { ...i.root, extraItems: [] } })), "input.invalid", "camelCase");
  assert.equal(refuses(i => ({ ...i, requests: [{ name: "writing-sync", agents: ["a"], exclude: ["b"] }] })), "filter.inconsistent");
}

